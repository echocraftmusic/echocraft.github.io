import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL(process.argv[2]||'../js/cart.js',import.meta.url),'utf8');
let stored=JSON.stringify([{id:'old',title:'Test single',type:'single',price:0.99,qty:4},{id:'duplicate',title:'Test single',type:'single',price:0.99,qty:3},{id:'merch:shirt',title:'Shirt',type:'merch',price:20,qty:2}]);
const nodes=Object.fromEntries(['.ec-cart-count','.ec-cart-quantity','.ec-cart-list','.ec-cart-total span:last-child','.ec-cart-checkout','.ec-cart-agree','.ec-cart-close'].map(key=>[key,{focus(){}}]));
const context={window:{},document:{readyState:'loading',addEventListener(){},querySelector:selector=>nodes[selector]||null,body:{classList:{add(){},remove(){}}}},localStorage:{getItem:()=>stored,setItem:(key,value)=>{stored=value;}}};
vm.runInNewContext(source,context);
let items=JSON.parse(stored);assert.equal(items.length,2);assert.equal(items[0].qty,1);assert.equal(items[1].qty,2);
context.window.EchoCraftCart.add({title:'Test single',type:'single',price:0.99});
context.window.EchoCraftCart.add({title:'Test single',type:'single',price:0.99});
items=JSON.parse(stored);assert.equal(items.length,2);assert.equal(items[0].qty,1);
assert.equal((nodes['.ec-cart-list'].innerHTML.match(/ec-cart-qty/g)||[]).length,1,'Only physical merchandise has quantity controls.');
assert.equal(nodes['.ec-cart-total span:last-child'].textContent,'$40.99');
context.window.EchoCraftCart.add({title:'Test album',type:'album',price:9.99});
context.window.EchoCraftCart.add({title:'Test album',type:'album',price:9.99});
assert.equal(JSON.parse(stored).find(item=>item.type==='album').qty,1);
assert.equal(nodes['.ec-cart-total span:last-child'].textContent,'$50.98');
console.log('Passed: existing digital quantities normalized, duplicate digital entries collapsed, repeated additions stay at one, merchandise quantities preserved, and totals match.');
